export function normalizeWord(str) {
  if (!str || typeof str !== "string") return "";
  return str.trim().toLowerCase().replace(/[^a-z0-9]/g, "");
}

export function validateStartingLetter(word, letter) {
  if (!word || !letter) return false;
  const cleanWord = word.trim();
  return cleanWord.length > 0 && cleanWord[0].toUpperCase() === letter.toUpperCase();
}

export function isKnownWord(category, word) {
  if (!LK_DICTIONARY[category] || !word) return false;
  const norm = normalizeWord(word);
  return LK_DICTIONARY[category].some(item => normalizeWord(item) === norm);
}

// Helper to get random sample words for bot play
export function getRandomWordForLetter(category, letter) {
  if (!LK_DICTIONARY[category] || !letter) return "";
  const filtered = LK_DICTIONARY[category].filter(w => 
    w.trim().toUpperCase().startsWith(letter.toUpperCase())
  );
  if (filtered.length === 0) {
    return letter.toUpperCase() + "item";
  }
  const randomIndex = Math.floor(Math.random() * filtered.length);
  return filtered[randomIndex];
}
